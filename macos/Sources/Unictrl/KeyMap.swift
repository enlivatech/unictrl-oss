    /// Device-dependent modifier bits in CGEventFlags, used to tell whether a modifier went down or up.
    static let modifierMask: [UInt16: UInt64] = [
        0x3B: 0x0000_0001, // left control
        0x38: 0x0000_0002, // left shift
        0x3C: 0x0000_0004, // right shift
        0x37: 0x0000_0008, // left command
        0x36: 0x0000_0010, // right command
        0x3A: 0x0000_0020, // left option
        0x3D: 0x0000_0040, // right option
        0x3E: 0x0000_2000, // right control
    ]

    static let capsLock: UInt16 = 0x39
    static let function: UInt16 = 0x3F

    /// NX_KEYTYPE_* media keys (NSSystemDefined subtype 8) to HID consumer usages (page 0x0C).
    static let media: [Int: UInt16] = [
        0: 0xE9,  // sound up
        2: 0x6F,  // brightness up: the PC changes its built-in screen
